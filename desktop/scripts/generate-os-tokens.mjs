import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const tokens = JSON.parse(await readFile(path.join(root, 'desktop/src/theme/os-tokens.json'), 'utf8'));
const rustPath = path.join(root, 'hub/crates/hh-shell/src/theme.rs');
const cssPath = path.join(root, 'desktop/src/style.css');
const ident = (key) => key.replace(/([a-z])([A-Z])/g, '$1_$2').replaceAll('.', '_').toUpperCase();
const kebab = (key) => key.replace(/([a-z])([A-Z])/g, '$1-$2').replaceAll('.', '-').toLowerCase();
const colors = Object.entries(tokens.colors);
const rust = ['// Generated by desktop/scripts/generate-os-tokens.mjs; edit os-tokens.json instead.', ''];
for (const [mode, values] of colors) {
  rust.push(`pub mod ${mode === 'highContrast' ? 'high_contrast' : mode} {`);
  for (const [key, value] of Object.entries(values)) rust.push(`    pub const ${ident(key)}: &str = ${JSON.stringify(value)};`);
  rust.push('}', '');
}
for (const [key, values] of Object.entries({spacing: tokens.spacing, typography_sizes: tokens.typography.sizes})) {
  rust.push(`pub const ${ident(key)}: [u16; ${values.length}] = [${values.join(', ')}];`);
}
for (const [group, values] of Object.entries({radii: tokens.radii, geometry: tokens.geometry, typography: tokens.typography})) {
  for (const [key, value] of Object.entries(values)) {
    if (Array.isArray(value)) {
      if (key === 'fontFamilies') rust.push(`pub const FONT_FAMILIES: [&str; ${value.length}] = [${value.map(JSON.stringify).join(', ')}];`);
    } else {
      rust.push(`pub const ${ident(`${group}_${key}`)}: ${Number.isInteger(value) ? 'u16' : 'f32'} = ${value};`);
    }
  }
}
await writeFile(rustPath, `${rust.join('\n')}\n`);

const start = '/* BEGIN GENERATED OS TOKENS */';
const end = '/* END GENERATED OS TOKENS */';
const declarations = (values) => Object.entries(values).map(([key, value]) => `  --os-${kebab(key)}: ${value};`).join('\n');
const aliases = `  --bg: var(--os-bg);\n  --surface: var(--os-surface);\n  --ink: var(--os-ink);\n  --accent: var(--os-accent);\n  --line: var(--os-divider);\n  --muted: var(--os-ink-secondary);\n  color: var(--ink);\n  background: var(--bg);`;
const numeric = [
  ...tokens.spacing.map((value) => [`spacing-${value}`, value]),
  ...Object.entries(tokens.radii).map(([key, value]) => [`radius-${kebab(key)}`, value]),
  ...Object.entries(tokens.geometry).map(([key, value]) => [`${kebab(key)}`, value]),
  ...tokens.typography.sizes.map((value) => [`font-size-${value}`, value]),
  ['font-body-size', tokens.typography.bodySize],
  ['focus-ring-width', tokens.typography.focusRingWidth],
  ['focus-ring-offset', tokens.typography.focusRingOffset],
];
const numericCss = numeric.map(([key, value]) => `  --os-${key}: ${value}px;`).join('\n');
const block = `${start}\n:root {\n${declarations(tokens.colors.dark)}\n${numericCss}\n  --os-line-height: ${tokens.typography.lineHeight};\n  --os-label-weight: ${tokens.typography.labelWeight};\n  --os-heading-weight: ${tokens.typography.headingWeight};\n  --os-font-family: ${tokens.typography.fontFamilies.map((name) => `"${name}"`).join(', ')}, sans-serif;\n${aliases}\n}\n:root[data-os-theme="light"] {\n${declarations(tokens.colors.light)}\n}\n:root[data-os-theme="high-contrast"] {\n${declarations(tokens.colors.highContrast)}\n}\n${end}`;
let css = await readFile(cssPath, 'utf8');
const begin = css.indexOf(start);
const finish = css.indexOf(end);
if ((begin === -1) !== (finish === -1)) throw new Error('Incomplete generated token block in style.css');
css = begin === -1 ? `${css.trimEnd()}\n\n${block}\n` : `${css.slice(0, begin)}${block}${css.slice(finish + end.length)}`;
await writeFile(cssPath, css);
